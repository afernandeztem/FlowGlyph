"""Context files for coding agents: `AGENTS.md`, `.claude/rules/project-context.md`, activity cards.

Coding agents read a project's `AGENTS.md` before working on it, and UiPath's own skills read
`.claude/rules/project-context.md`, writing it with a language model when it is missing. This
module writes both from the catalog instead, in the same sections, so every fact in them is
read from the sources: arguments with their exact types, entry points, the call tree. It adds
what a model can only guess: what each workflow does to the world and whether it is safe to run
twice. For every activity a project uses, it also writes a card with a XAML template taken from
the project's own use of it.

Everything a person writes below the notes marker of a generated file is kept when it is
written again. A file FlowGlyph did not write is never overwritten without `force`.
"""

from collections import Counter, defaultdict
from collections.abc import Iterable, Mapping
from dataclasses import dataclass
from pathlib import Path, PurePosixPath
from typing import Any, cast

from flowglyph import report
from flowglyph.adapters.uipath import UiPathAdapter
from flowglyph.adapters.uipath.project import Project, read_project
from flowglyph.catalog import Catalog
from flowglyph.ir import Capability, Parameter
from flowglyph.views import effects_code, retry_advice

MARKER = "<!-- generated by flowglyph context from the sources, without a language model -->"
NOTES_MARKER = "<!-- flowglyph:notes -->"
AGENTS_FILE = "AGENTS.md"
RULES_FILE = ".claude/rules/project-context.md"
CARDS_DIRECTORY = ".flowglyph/activities"
_ROWS = 12
_ARGUMENTS_SHOWN = 6
_NOTES = f"""{NOTES_MARKER}
## Notes

_Everything below this line is kept when the file is generated again._
"""


@dataclass(frozen=True)
class Written:
    """What writing the context did to one file."""

    path: Path
    action: str


def project_files(catalog: Catalog, project: Project) -> dict[str, str]:
    """The context files of one UiPath project, by path relative to its root."""
    prefix = f"uipath/{project.slug}/"
    workflows = sorted(
        (c for c in catalog if c.id.startswith(prefix) and c.kind == "workflow"),
        key=lambda c: c.source.location,
    )
    activities = [
        capability
        for capability in UiPathAdapter().extract(project.root).capabilities
        if capability.kind == "activity"
    ]
    document = _Document(project, workflows, activities, catalog).render()
    files = {AGENTS_FILE: document, RULES_FILE: document}
    for activity in activities:
        files[f"{CARDS_DIRECTORY}/{activity.title}.md"] = _card(activity, project)
    return files


def projects(root: Path) -> list[Project]:
    """Every UiPath project under `root`."""
    return [read_project(path) for path in UiPathAdapter().discover(root) if path.is_dir()]


def write(root: Path, files: Mapping[str, str], *, force: bool = False) -> list[Written]:
    """Write `files` under `root`, keeping notes, and never replacing a file a person wrote."""
    written: list[Written] = []
    for relative, text in files.items():
        path = root / relative
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current is not None and MARKER not in current and not force:
            written.append(Written(path, "kept: not written by flowglyph, use --force"))
            continue
        notes = _NOTES
        if current is not None and NOTES_MARKER in current:
            notes = current[current.index(NOTES_MARKER) :]
        body = text.rstrip("\n") + "\n\n" + notes.rstrip("\n") + "\n"
        if body == current:
            written.append(Written(path, "unchanged"))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body, encoding="utf-8", newline="\n")
        written.append(Written(path, "updated" if current is not None else "created"))
    return written


class _Document:
    def __init__(
        self,
        project: Project,
        workflows: list[Capability],
        activities: list[Capability],
        catalog: Catalog,
    ) -> None:
        self.project = project
        self.workflows = workflows
        self.activities = activities
        self.catalog = catalog
        self.by_file: defaultdict[str, list[str]] = defaultdict(list)
        for activity in activities:
            for file in activity.used_in:
                self.by_file[file].append(activity.title)
        self.lines: list[str] = []

    def render(self) -> str:
        files = sorted(
            p
            for p in self.project.root.rglob("*")
            if p.is_file() and not _hidden(p, self.project.root)
        )
        counts = Counter(p.suffix.lower() for p in files)
        self.lines = [
            (
                f"<!-- discovery-metadata: cs={counts['.cs']} xaml={counts['.xaml']} "
                f"deps={len(self.project.dependencies)} -->"
            ),
            MARKER,
            f"# {self.project.name} — Project Context",
            "",
            (
                "> Generated by FlowGlyph from the project's files, without a language model: "
                "every fact below is read from them. Regenerate with `flowglyph context .` after "
                "changes."
            ),
            "",
        ]
        self._overview()
        self._dependencies()
        self._structure(files, counts)
        self._entry_points()
        self._key_workflows()
        self._retry_safety()
        self._call_tree()
        self._architecture()
        self._conventions()
        self._open_questions()
        self._cards()
        self._quick_reference()
        return "\n".join(self.lines).rstrip("\n") + "\n"

    def _section(self, title: str, rows: Iterable[str]) -> None:
        body = list(rows)
        if body:
            self.lines += [f"## {title}", "", *body, ""]

    def _overview(self) -> None:
        project = self.project
        values = [
            ("Name", project.name),
            ("Type", project.output_type),
            ("Description", project.description),
            ("Main", f"`{project.main}`"),
            ("Expression Language", project.expression_language),
            ("Target Framework", project.target_framework),
            ("Studio Version", project.studio_version),
        ]
        rows = [f"| **{name}** | {_cell(value)} |" for name, value in values if value]
        self._section("Overview", ["| Property | Value |", "|---|---|", *rows])

    def _dependencies(self) -> None:
        items = sorted(self.project.dependencies.items())
        rows = [f"| {name} | {version} |" for name, version in items]
        if rows:
            self._section("Dependencies", ["| Package | Version |", "|---|---|", *rows])

    def _structure(self, files: list[Path], counts: Counter[str]) -> None:
        folders: Counter[str] = Counter()
        for file in files:
            relative = file.relative_to(self.project.root)
            folders[relative.parts[0] + "/" if len(relative.parts) > 1 else "."] += (
                file.suffix.lower() == ".xaml"
            )
        tree = [f"{self.project.root.name}/"]
        for folder, xaml in sorted(folders.items()):
            if folder != "." and xaml:
                tree.append(f"├── {folder:<24} # {xaml} workflow{'s' if xaml != 1 else ''}")
        tree.append(f"└── {self.project.main}")
        table = [
            "| File Type | Count |",
            "|---|---|",
            f"| RPA workflows (.xaml) | {counts['.xaml']} |",
        ]
        if counts[".cs"]:
            table.append(f"| Coded workflows (.cs) | {counts['.cs']} |")
        self._section("Project Structure", ["```", *tree, "```", "", *table])

    def _entry_points(self) -> None:
        entries = [w for w in self.workflows if w.source.location in self.project.entry_points]
        rows = [
            f"| `{w.source.location}` | {_arguments(w.inputs)} | {_arguments(w.outputs)} | "
            f"{_cell(_first_sentence(w.description))} |"
            for w in entries
        ]
        header = ["| File | Input Arguments | Output Arguments | Purpose |", "|---|---|---|---|"]
        self._section("Entry Points", [*header, *rows] if rows else [])

    def _key_workflows(self) -> None:
        rows = [
            f"| `{w.source.location}` | {_cell(_first_sentence(w.description))} | "
            f"{_cell(', '.join(sorted(set(self.by_file[w.source.location]) - _PLUMBING)[:6]))} |"
            for w in self.workflows
        ]
        header = ["| Workflow | Purpose | Activities Used |", "|---|---|---|"]
        self._section("Key Workflows", _capped([*header, *rows], "`flowglyph inspect .`"))

    def _retry_safety(self) -> None:
        rows = [
            f"| `{w.source.location}` | {effects_code(w.effects) or 'none'} | "
            f"{w.idempotency.mode} | {report.status(w)} | {_cell(retry_advice(w.idempotency))} |"
            for w in self.workflows
        ]
        intro = [
            (
                "What each workflow does to the world, computed from its activities and the "
                "workflows it invokes. Effects: `R`ead, `W`rite, `D`estroy, e`X`ternal; upper "
                "case is yes, lower case is unknown. A workflow marked `review` changes something"
                " and nothing says it is safe to run twice: do not retry it blindly."
            ),
            "",
            "| Workflow | Effects | Idempotency | Status | Retrying |",
            "|---|---|---|---|---|",
        ]
        self._section(
            "Effects and Retry Safety", _capped([*intro, *rows], "`flowglyph idempotency .`")
        )

    def _call_tree(self) -> None:
        called = {c for w in self.workflows for c in self._calls(w.id)}
        roots = [w for w in self.workflows if w.entry_point] or [
            w for w in self.workflows if w.id not in called
        ]
        lines: list[str] = []
        for root in roots:
            self._grow(root, 0, frozenset({root.id}), lines)
        self._section("Call Tree", ["```", *lines[:40], "```"] if lines else [])

    def _grow(
        self, capability: Capability, depth: int, seen: frozenset[str], lines: list[str]
    ) -> None:
        indent = "    " * (depth - 1) + "└── " if depth else ""
        effects = effects_code(capability.effects) or "pure"
        lines.append(f"{indent}{capability.title} ({effects}, {capability.idempotency.mode})")
        for callee in self._calls(capability.id):
            target = self.catalog.capabilities.get(callee)
            if target is not None and callee not in seen:
                self._grow(target, depth + 1, seen | {callee}, lines)

    def _calls(self, capability_id: str) -> tuple[str, ...]:
        workflow = self.catalog.workflows.get(capability_id)
        return workflow.calls if workflow else ()

    def _architecture(self) -> None:
        locations = {w.source.location for w in self.workflows}
        reframework = {"Framework/GetTransactionData.xaml", "Framework/SetTransactionStatus.xaml"}
        if reframework <= locations:
            pattern = (
                "Robotic Enterprise Framework: a state machine that takes transactions one by one"
            )
        elif len(self.workflows) > 1:
            pattern = (
                f"`{self.project.main}` orchestrates {len(self.workflows) - 1} other workflows"
            )
        else:
            pattern = "Single workflow"
        external: defaultdict[str, list[str]] = defaultdict(list)
        for activity in self.activities:
            if activity.effects.external.possible and activity.category not in {
                "control",
                "logging",
            }:
                external[activity.category].append(activity.title)
        integrations = "; ".join(
            f"{category} ({', '.join(sorted(names)[:4])})"
            for category, names in sorted(external.items())
        )
        rows = [f"- **Pattern**: {pattern}"]
        if integrations:
            rows.append(f"- **External integrations**: {integrations}")
        self._section("Architecture", rows)

    def _conventions(self) -> None:
        arguments = [p.name for w in self.workflows for p in (*w.inputs, *w.outputs)]
        prefixed = sum(1 for name in arguments if name.startswith(("in_", "out_", "io_")))
        rows: list[str] = []
        if arguments:
            rows.append(
                f"- **Arguments**: {prefixed} of {len(arguments)} use the `in_` / `out_` / `io_` "
                "direction prefixes"
            )
        if self.project.expression_language:
            rows.append(f"- **Expressions**: {self.project.expression_language}")
        folders = sorted(
            {
                PurePosixPath(w.source.location).parts[0]
                for w in self.workflows
                if "/" in w.source.location
            }
        )
        if folders:
            rows.append(f"- **Folders**: {', '.join(f'`{folder}/`' for folder in folders)}")
        self._section("Conventions", rows)

    def _open_questions(self) -> None:
        rows = [
            f"- `{w.source.location}`: has side effects and no retry guarantee; declare its "
            "idempotency in `flowglyph.overrides.yaml`"
            for w in self.workflows
            if report.status(w) == "review"
        ]
        rows += [
            f"- `{w.source.location}`: {note.removeprefix('warning: ')}"
            for w in self.workflows
            for note in w.notes
        ]
        unresolved = {
            call
            for w in self.workflows
            if (graph := self.catalog.workflows.get(w.id))
            for call in graph.unresolved_calls
        }
        rows += [f"- invokes something not in the project: `{call}`" for call in sorted(unresolved)]
        self._section("Open Questions", rows[:_ROWS])

    def _cards(self) -> None:
        rows = [
            f"| {a.title} | {a.category} | {effects_code(a.effects) or 'none'} | "
            f"[{a.title}.md]({CARDS_DIRECTORY}/{a.title}.md) |"
            for a in sorted(self.activities, key=lambda a: a.title)
            if a.title not in _PLUMBING
        ]
        intro = [
            (
                "How this project uses each activity, with a XAML template from its own "
                "workflows. Read the card before adding or changing one."
            ),
            "",
            "| Activity | Category | Effects | Card |",
            "|---|---|---|---|",
        ]
        self._section(
            "Activity Cards", _capped([*intro, *rows], f"`{CARDS_DIRECTORY}/`") if rows else []
        )

    def _quick_reference(self) -> None:
        main = self.project.main
        invoked = Counter(call for w in self.workflows for call in self._calls(w.id))
        busiest = [
            self.catalog.capabilities[call].source.location
            for call, _ in invoked.most_common(2)
            if call in self.catalog.capabilities
        ]
        rows = [
            "- **Effects and retry safety**: `flowglyph idempotency .`",
            (
                "- **Call tree and workflow cards**: `flowglyph inspect .`, `flowglyph inspect . "
                "<workflow>`"
            ),
            (
                "- **Run** (UiPath CLI): "
                f'`uip rpa run --file-path "{main}" --project-dir "." --output json`'
            ),
            f"- **Key files to read first**: {', '.join(f'`{f}`' for f in [main, *busiest])}",
        ]
        self._section("Quick Reference", rows)


_PLUMBING = frozenset(
    {"Sequence", "Assign", "If", "LogMessage", "Comment", "Flowchart", "FlowDecision", "TryCatch",
     "Throw", "Rethrow", "ForEach", "ForEachRow", "While", "DoWhile", "Switch", "State",
     "StateMachine", "Transition", "InvokeWorkflowFile", "MultipleAssign", "AddLogFields",
     "RemoveLogFields", "ShouldStop", "Delay", "WriteLine"}
)  # fmt: skip


def _card(activity: Capability, project: Project) -> str:
    template = cast("dict[str, Any] | None", activity.input_schema.get("x-xaml-template"))
    properties = cast("dict[str, Any]", activity.input_schema.get("properties", {}))
    namespace = activity.source.artifact.split("}", 1)[0].lstrip("{")
    lines = [
        MARKER,
        f"# {activity.title} — as used in {project.name}",
        "",
        f"- **Category**: {activity.category}",
        f"- **Effects**: {effects_code(activity.effects) or 'none'} ({_effects_words(activity)})",
        f"- **Namespace**: `{namespace}`",
        f"- **Used in**: {', '.join(f'`{file}`' for file in activity.used_in[:10])}",
        "",
    ]
    if template:
        declarations = [
            f'xmlns{":" + prefix if prefix else ""}="{uri}"'
            for prefix, uri in cast("dict[str, str]", template.get("namespaces", {})).items()
        ]
        lines += [
            "## Template",
            "",
            (
                f"From `{template.get('from')}`, its richest use in this project. Replace each "
                "`[placeholder]` with this workflow's value; `<!-- activities -->` marks where "
                "child activities go. The root element of the workflow must declare:"
            ),
            "",
            "```xml",
            *declarations,
            "```",
            "",
            "```xml",
            str(template.get("xml", "")),
            "```",
            "",
        ]
    rows = [
        f"| `{name}` | {spec.get('x-seen', '')} | "
        f"{_cell(', '.join(cast('list[str]', spec.get('x-clr-types', []))))} |"
        for name, spec in sorted(properties.items())
    ]
    if rows:
        lines += [
            "## Properties Set in This Project",
            "",
            "| Property | Uses | Types |",
            "|---|---|---|",
            *rows,
            "",
        ]
    lines += [
        "## Retrying",
        "",
        (
            f"{retry_advice(activity.idempotency).capitalize()}. A workflow that uses this "
            "activity inherits its effects; check the workflow's retry safety in `AGENTS.md` "
            "before retrying it."
        ),
    ]
    return "\n".join(lines) + "\n"


def _effects_words(activity: Capability) -> str:
    effects = activity.effects
    words = [
        word
        for word, value in (
            ("reads", effects.reads),
            ("changes state", effects.mutates_state),
            ("can destroy data", effects.destructive),
            ("calls other systems", effects.external),
        )
        if value.possible
    ]
    return ", ".join(words) or "no effects outside the workflow"


def _arguments(parameters: list[Parameter]) -> str:
    if not parameters:
        return "none"
    shown = ", ".join(
        f"`{p.name}`: {p.type}{' or null' if p.nullable else ''}"
        for p in parameters[:_ARGUMENTS_SHOWN]
    )
    hidden = len(parameters) - _ARGUMENTS_SHOWN
    return shown + (f", and {hidden} more" if hidden > 0 else "")


def _capped(rows: list[str], more: str) -> list[str]:
    """A table cut to `_ROWS` data rows, saying where to see the rest."""
    header = next((i for i, row in enumerate(rows) if row.startswith("|---")), -1) + 1
    data = rows[header:]
    if len(data) <= _ROWS:
        return rows
    return [*rows[:header], *data[:_ROWS], "", f"_...and {len(data) - _ROWS} more: {more}_"]


def _first_sentence(text: str) -> str:
    first = text.strip().split("\n", 1)[0]
    for end in (". ", "? ", "! "):
        if end in first:
            first = first.split(end, 1)[0] + end.strip()
    return first[:160]


def _cell(value: object) -> str:
    return str(value or "").replace("|", "\\|").replace("\n", " ").strip()


def _hidden(path: Path, root: Path) -> bool:
    return any(part.startswith(".") for part in path.relative_to(root).parts)
